/// Factory program `k`'s value for parameter `i`.
pub fn value(k: usize, i: usize) -> f32 {
    let (_, list) = FACTORY[k.min(PROGRAMS - 1)];
    list.iter()
        .rev()
        .find(|(p, _)| *p == i)
        .map_or(DEF.params[i].default, |&(_, v)| v)
}

pub fn name(k: usize) -> &'static str {
    FACTORY[k.min(PROGRAMS - 1)].0
}

/// The effects' order a factory program uses: tape after the echoes on the
/// worn tape sounds, the usual order elsewhere.
pub fn fx_order(k: usize) -> [usize; 5] {
    match name(k) {
        "Tape Sequence" | "Tape Pad" | "Lo-Fi Drone" => [1, 0, 2, 3, 4],
        _ => [0, 1, 2, 3, 4],
    }
}
